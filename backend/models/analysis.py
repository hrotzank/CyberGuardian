from datetime import datetime, timezone
from sqlalchemy import Column, Integer, String, Float, Text, DateTime, JSON
from backend.database.connection import Base

class AnalysisRecord(Base):
    """
    SQLAlchemy model representing a phishing analysis record.
    Stores metadata and results generated by the multi-agent system.
    """
    __tablename__ = "analysis_records"

    id = Column(Integer, primary_key=True, index=True)
    content = Column(Text, nullable=False)
    source = Column(String(50), default="web", nullable=False)
    risk_score = Column(Float, nullable=False)
    risk_level = Column(String(20), nullable=False)
    
    # Store structures list[str] as JSON
    findings = Column(JSON, nullable=False)
    recommendations = Column(JSON, nullable=False)
    
    educational_explanation = Column(Text, nullable=False)
    created_at = Column(DateTime, default=lambda: datetime.now(timezone.utc), nullable=False)
